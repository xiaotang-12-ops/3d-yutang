"""把原始C++程序网格的同一顶点/索引/法线/UV通过原生组件存入实验关卡；仅做裁取与单位桥接。-codex，2026-10-23"""
import unreal,json,pathlib
ROOT=pathlib.Path('D:/3d-research/experiments/fujian-mountain-art-ab')
OUT=pathlib.Path('D:/3d-research/artifacts/fujian-mountain-art-ab')
data=json.loads((ROOT/'sample.json').read_text())
level=unreal.get_editor_subsystem(unreal.LevelEditorSubsystem)
actors=unreal.get_editor_subsystem(unreal.EditorActorSubsystem)
assert level.new_level('/Game/ArtAB/Original')
world=unreal.UnrealEditorSubsystem().get_editor_world()
world.get_world_settings().set_editor_property('default_game_mode',unreal.GameModeBase.static_class())
terrain=actors.spawn_actor_from_class(unreal.Actor,unreal.Vector())
terrain.set_actor_label('Original_CPP_ProceduralMesh_SameData')
pm=terrain.call_method('AddComponentByClass',args=(unreal.ProceduralMeshComponent.static_class(),False,unreal.Transform(),False))
pm.create_mesh_section_linear_color(0,[unreal.Vector(*p) for p in data['vertices']],data['triangles'],[unreal.Vector(*p) for p in data['normals']],[unreal.Vector2D(*p) for p in data['uv']],[],[],[],[],[],True,False)
pm.set_material(0,unreal.load_asset('/Game/Terrain/M_Terrain'))
pm.set_editor_property('use_complex_as_simple_collision',True)
sun=actors.spawn_actor_from_class(unreal.DirectionalLight,unreal.Vector(0,0,1000000),unreal.Rotator(-38,-42,0))
sun.set_actor_label('AB_Common_Sun')
sun.light_component.set_editor_property('intensity',80000.0)
sun.light_component.set_editor_property('atmosphere_sun_light',True)
sun.light_component.set_editor_property('dynamic_shadow_distance_movable_light',4000000.0)
sky=actors.spawn_actor_from_class(unreal.SkyAtmosphere,unreal.Vector())
sky.set_actor_label('AB_Common_Atmosphere')
skylight=actors.spawn_actor_from_class(unreal.SkyLight,unreal.Vector(0,0,1000000))
skylight.set_actor_label('AB_Common_SkyLight')
skylight.light_component.set_editor_property('real_time_capture',True)
pp=actors.spawn_actor_from_class(unreal.PostProcessVolume,unreal.Vector())
pp.set_actor_label('AB_Common_FixedExposure')
pp.set_editor_property('unbound',True)
settings=pp.get_editor_property('settings')
settings.set_editor_property('override_auto_exposure_method',True)
settings.set_editor_property('auto_exposure_method',unreal.AutoExposureMethod.AEM_MANUAL)
settings.set_editor_property('override_auto_exposure_bias',True)
settings.set_editor_property('auto_exposure_bias',0.0)
settings.set_editor_property('override_camera_iso',True)
settings.set_editor_property('camera_iso',100.0)
settings.set_editor_property('override_camera_shutter_speed',True)
settings.set_editor_property('camera_shutter_speed',125.0)
settings.set_editor_property('override_depth_of_field_fstop',True)
settings.set_editor_property('depth_of_field_fstop',11.0)
settings.set_editor_property('override_auto_exposure_apply_physical_camera_exposure',True)
settings.set_editor_property('auto_exposure_apply_physical_camera_exposure',True)
settings.set_editor_property('override_motion_blur_amount',True)
settings.set_editor_property('motion_blur_amount',0.0)
pp.set_editor_property('settings',settings)
cameras={}
for name,location,target in [('Normal',(-1550000,-1200000,1350000),(0,0,250000)),('Close',(-530000,-340000,510000),(100000,120000,220000))]:
    rotation=unreal.MathLibrary.find_look_at_rotation(unreal.Vector(*location),unreal.Vector(*target))
    camera=actors.spawn_actor_from_class(unreal.CameraActor,unreal.Vector(*location),rotation)
    camera.set_actor_label('AB_Camera_'+name)
    camera.camera_component.set_editor_property('field_of_view',55.0)
    camera.camera_component.set_editor_property('constrain_aspect_ratio',True)
    camera.camera_component.set_editor_property('aspect_ratio',1920/1080)
    if name=='Normal': camera.set_editor_property('auto_activate_for_player',unreal.AutoReceiveInput.PLAYER0)
    cameras[name]={'location':location,'target':target,'rotation':[rotation.pitch,rotation.yaw,rotation.roll],'fov':55.0}
    if name=='Normal':unreal.EditorLevelLibrary.set_level_viewport_camera_info(unreal.Vector(*location),rotation)
unreal.SystemLibrary.execute_console_command(world,'r.ScreenPercentage 100')
unreal.SystemLibrary.execute_console_command(world,'r.SetRes 1920x1080w')
assert level.save_current_level()
(OUT/'fixed-cameras.json').write_text(json.dumps(cameras,indent=2),encoding='utf-8')
(OUT/'original-bindings.json').write_text(json.dumps({'terrainComponent':pm.get_path_name(),'nativeClass':pm.get_class().get_path_name(),'material':pm.get_material(0).get_path_name(),'sunIntensityLux':sun.light_component.intensity,'sunRotation':str(sun.get_actor_rotation()),'exposure':'Manual ISO100 1/125 f11; bias0','vertices':len(data['vertices']),'triangles':len(data['triangles'])//3},indent=2),encoding='utf-8')
